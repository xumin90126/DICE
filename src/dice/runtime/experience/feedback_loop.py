"""
Phase 4.3: Feedback Loop — ExperienceGraph, HealthReport, EvolutionProposal.

Architecture (corrected):
    ExecutionExperience (from Runtime)
            │
            ▼
    ExperienceGraph.write(exp)         ← write/persist/route ONLY
            │
            ├── Persist (JSONL)        ← filesystem write
            ├── Evidence.produce()     ← Experience → Evidence transformation
            │       │
            │       ▼
            │   EvidenceView           ← Registry reads from this
            │       │
            │       ▼
            │   Registry.consume_evidence()  ← reads EvidenceView, updates stats
            │
            └── Accumulator            ← in-memory for HealthReport
                    │
                    ▼
                HealthReport            ← descriptive ONLY
                    │
                    ▼
                EvolutionProposal       ← when signals warrant (draft status)

CRITICAL DESIGN:
    1. ExperienceGraph does NOT directly modify Capability/Implementation/Rule
    2. Evidence is produced FROM experience, Registry reads EvidenceView
    3. HealthReport is DESCRIPTIVE — not prescriptive
    4. EvolutionProposal requires Validation Gate for promotion beyond "proposed"
    5. EnhancementSignal says "I noticed" — not "do this"
    6. NO auto Capability change before Validation Gate
"""

from __future__ import annotations

import json
import os
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Optional

from dice.evidence import Evidence, EvidenceView, EvidenceStore, EvidenceType
from dice.runtime.experience.execution_models import ExecutionExperience

# Avoid circular imports — types are referenced by string where needed


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _uid(prefix: str = "") -> str:
    """Generate a short unique ID."""
    return f"{prefix}{uuid.uuid4().hex[:8]}"


