# EnhancementSignal
# ═══════════════════════════════════════════════════════════════════════════


@dataclass
class EnhancementSignal:
    """
    A signal that the system noticed something that COULD warrant attention.

    DESCRIPTIVE ONLY — says "I noticed X", NOT "you should do Y".

    Signals are data points generated from accumulated ExecutionExperiences.
    They are the raw material that EvolutionProposals are built from, but
    a signal alone does NOT trigger any change.

    Example:
        EnhancementSignal(
            signal_type="vocabulary_gap",
            severity="warning",
            description="Term 'cell lysis buffer' appeared in 3 failures but is not in capability vocabulary",
            evidence={"missing_terms": ["cell lysis buffer"], "failure_count": 3},
        )
        # NOT:
        # EnhancementSignal(
        #     signal_type="vocabulary_gap",
        #     severity="warning",
        #     description="Add 'cell lysis buffer' to capability vocabulary",
        #     evidence={"missing_terms": ["cell lysis buffer"]},
        # )
    """

    signal_type: str = ""         # "vocabulary_gap", "pattern_mismatch", "confidence_drop",
                                  # "high_failure_rate", "cross_domain_failure",
                                  # "implementation_underperformance", "insufficient_data",
                                  # "performance_degrading", "recurring_failure_pattern"
    severity: str = "info"        # "info", "warning", "critical"
    description: str = ""
    evidence: dict[str, Any] = field(default_factory=dict)
    generated_at: str = field(default_factory=_now)

    def to_dict(self) -> dict[str, Any]:
        return {
            "signal_type": self.signal_type,
            "severity": self.severity,
            "description": self.description,
            "evidence": self.evidence,
            "generated_at": self.generated_at,
        }


