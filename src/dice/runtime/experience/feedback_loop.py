@dataclass
class HealthReport:
    """
    Per-Capability health assessment derived from accumulated experiences.

    DESCRIPTIVE ONLY — describes what the data shows, does NOT prescribe
    what to do. Generated by ExperienceGraph.compute_health().

    Computed fields:
        trend: "improving" if recent success > historical, "degrading" if worse,
               "stable" otherwise.
        confidence_trend: same logic applied to confidence scores.
        top_failure_reasons: most common failure reasons from recent failures.
        signals: EnhancementSignals derived from the data.
    """

    capability_id: str = ""
    capability_name: str = ""

    # ── Execution statistics ──
    total_executions: int = 0
    success_count: int = 0
    failure_count: int = 0
    success_rate: float = 0.0

    # ── Trend analysis (recent window vs historical) ──
    recent_success_rate: float = 0.0       # last N executions
    recent_window_size: int = 20
    trend: str = "stable"                  # "improving", "stable", "degrading"

    # ── Failure analysis ──
    top_failure_reasons: list[dict[str, Any]] = field(default_factory=list)
    # [{"reason": "no_capability_match", "count": 5, "pct": 50.0}, ...]

    # ── Confidence analysis ──
    avg_confidence: float = 0.0
    confidence_trend: str = "stable"       # "improving", "stable", "degrading"

    # ── Signals (NOT prescriptions) ──
    signals: list[EnhancementSignal] = field(default_factory=list)

    # ── Metadata ──
    generated_at: str = field(default_factory=_now)
    data_window_start: str = ""
    data_window_end: str = ""
    experience_ids_analyzed: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "capability_id": self.capability_id,
            "capability_name": self.capability_name,
            "total_executions": self.total_executions,
            "success_count": self.success_count,
            "failure_count": self.failure_count,
            "success_rate": round(self.success_rate, 4),
            "recent_success_rate": round(self.recent_success_rate, 4),
            "recent_window_size": self.recent_window_size,
            "trend": self.trend,
            "top_failure_reasons": self.top_failure_reasons,
            "avg_confidence": round(self.avg_confidence, 4),
            "confidence_trend": self.confidence_trend,
            "signals": [s.to_dict() for s in self.signals],
            "generated_at": self.generated_at,
            "experience_ids_analyzed": len(self.experience_ids_analyzed),
        }

    def has_critical_signals(self) -> bool:
        """Check if there are any critical-severity signals."""
        return any(s.severity == "critical" for s in self.signals)

    def has_actionable_signals(self) -> bool:
        """Check if there are warning-or-above signals that warrant a proposal."""
        return any(s.severity in ("warning", "critical") for s in self.signals)


