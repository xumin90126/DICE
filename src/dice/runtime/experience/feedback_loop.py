@dataclass
class EvolutionProposal:
    """
    A structured proposal for evolving a Capability.

    Generated when HealthReport detects actionable signals. Does NOT
    auto-apply — must go through Validation Gate.

    Status lifecycle:
        draft      — generated but not yet reviewed
        proposed   — submitted for validation
        validated  — passed through Validation Gate
        applied    — changes have been applied (external action)
        rejected   — did not pass Validation Gate or was declined

    The Feedback Loop CANNOT move status beyond "proposed". Only the
    Validation Gate can set "validated", "applied", or "rejected".
    """

    id: str = ""
    capability_id: str = ""
    capability_name: str = ""
    proposal_type: str = ""         # "vocabulary_gap_observed", "pattern_coverage_gap",
                                    # "confidence_instability", "scope_boundary_uncertain",
                                    # "performance_degradation", "recurring_failure_pattern",
                                    # "implementation_strategy_mismatch"

    # ── Source trace (MANDATORY) ──
    trigger_signals: list[EnhancementSignal] = field(default_factory=list)
    trigger_experience_ids: list[str] = field(default_factory=list)
    trigger_evidence_ids: list[str] = field(default_factory=list)    # 🆕 evidence trace
    health_at_generation: Optional[HealthReport] = None

    # ── What was observed (NOT what to do) ──
    observed_phenomenon: dict[str, Any] = field(default_factory=dict)
    # Structured description of WHAT was observed:
    #   vocabulary_gap_observed: {"domain": "components", "unmatched_terms_frequency": {...}}
    #   performance_degradation: {"recent_rate": 0.4, "historical_rate": 0.8, "delta": -0.4}
    #   pattern_coverage_gap: {"unmatched_structure_types": ["collapsed_table_variant_2"]}

    # ── Rationale (why this matters, not what to change) ──
    rationale: str = ""

    # ── Validation requirements ──
    validation_required: list[str] = field(default_factory=list)
    # e.g. ["regression_guard", "cross_document_check", "confidence_threshold"]
    validation_results: list[dict[str, Any]] = field(default_factory=list)
    # e.g. [{"gate": "regression_guard", "passed": True, "detail": "..."}]

    # ── Status ──
    status: str = "draft"           # "draft" → "proposed" → "validated" → "applied" | "rejected"

    # ── Metadata ──
    created_at: str = field(default_factory=_now)
    updated_at: str = field(default_factory=_now)
    created_by: str = "feedback_loop"
    notes: list[str] = field(default_factory=list)

    def __post_init__(self):
        if not self.id:
            self.id = _uid("EVO-PROP-")

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "capability_id": self.capability_id,
            "capability_name": self.capability_name,
            "proposal_type": self.proposal_type,
            "trigger_signal_types": [s.signal_type for s in self.trigger_signals],
            "trigger_experience_count": len(self.trigger_experience_ids),
            "trigger_evidence_count": len(self.trigger_evidence_ids),
            "observed_phenomenon": self.observed_phenomenon,
            "rationale": self.rationale[:500],
            "validation_required": self.validation_required,
            "validation_results": self.validation_results,
            "status": self.status,
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "notes": self.notes,
        }

    def submit(self) -> None:
        """Submit for validation (status: draft → proposed)."""
        if self.status == "draft":
            self.status = "proposed"
            self.updated_at = _now()
            self.notes.append(f"[{_now()}] Submitted for validation")

    def validate(self, results: list[dict[str, Any]]) -> None:
        """
        Record validation results (called by Validation Gate only).
        Status: proposed → validated | rejected.
        """
        if self.status != "proposed":
            return
        self.validation_results = results
        all_passed = all(r.get("passed", False) for r in results)
        self.status = "validated" if all_passed else "rejected"
        self.updated_at = _now()
        self.notes.append(
            f"[{_now()}] Validation {'passed' if all_passed else 'failed'}: "
            f"{len([r for r in results if r.get('passed')])}/{len(results)} gates"
        )

    def mark_applied(self) -> None:
        """Mark as applied (external action completed)."""
        self.status = "applied"
        self.updated_at = _now()
        self.notes.append(f"[{_now()}] Changes applied")

    def mark_rejected(self, reason: str = "") -> None:
        """Reject the proposal."""
        self.status = "rejected"
        self.updated_at = _now()
        if reason:
            self.notes.append(f"[{_now()}] Rejected: {reason}")

    def can_be_promoted(self) -> bool:
        """Can this proposal move to 'proposed'?"""
        return self.status == "draft"

    def needs_validation(self) -> bool:
        """Does this proposal still need validation?"""
        return self.status in ("draft", "proposed")


