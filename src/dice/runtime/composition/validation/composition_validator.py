# ═══════════════════════════════════════════════════════════════════════════
# Enums
# ═══════════════════════════════════════════════════════════════════════════


class ValidationStage(Enum):
    """9-stage validation pipeline."""

    GRAPH_CONSISTENCY = "graph_consistency"
    DEPENDENCY_CHECK = "dependency_check"
    CONFLICT_DETECTION = "conflict_detection"
    RULE_COMPLIANCE = "rule_compliance"
    EXECUTION_ORDER = "execution_order"
    GOVERNANCE_CHAIN = "governance_chain"
    RISK_ASSESSMENT = "risk_assessment"
    SEMANTIC_COHERENCE = "semantic_coherence"
    FINAL_APPROVAL = "final_approval"


class ValidationDimension(Enum):
    """8 validation dimensions."""

    STRUCTURAL = "structural"           # Graph structure integrity
    DEPENDENCY = "dependency"           # Dependency correctness
    CONFLICT = "conflict"               # Conflict resolution
    RULE = "rule"                       # Rule compliance
    EXECUTION = "execution"             # Execution feasibility
    GOVERNANCE = "governance"           # Governance chain completeness
    RISK = "risk"                       # Risk acceptability
    SEMANTIC = "semantic"               # Semantic coherence


# ═══════════════════════════════════════════════════════════════════════════
# Data Models
# ═══════════════════════════════════════════════════════════════════════════


@dataclass
class StageCheckResult:
    """Result of a single validation stage check."""

    stage: ValidationStage = ValidationStage.GRAPH_CONSISTENCY
    passed: bool = False
    checks_total: int = 0
    checks_passed: int = 0
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ConflictRecord:
    """Record of a conflict detected during validation."""

    conflict_type: str = ""
    capability_ids: List[str] = field(default_factory=list)
    description: str = ""
    severity: str = "WARNING"  # WARNING, ERROR, BLOCKER
    resolution: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class RiskAssessment:
    """Risk assessment for a composition proposal."""

    overall_score: float = 0.0          # 0-1, higher = more risky
    risk_factors: List[str] = field(default_factory=list)
    risk_level: str = "UNKNOWN"         # LOW, MEDIUM, HIGH, CRITICAL
    mitigations: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class CompositionValidationResult:
    """Complete validation result for a composition proposal.

    Phase 6.0: Schema only. Generated by ValidationEngine in Phase 6.1+.
    """

    proposal_id: str = ""
    passed: bool = False
    stage_results: List[StageCheckResult] = field(default_factory=list)
    conflicts: List[ConflictRecord] = field(default_factory=list)
    risk: RiskAssessment = field(default_factory=RiskAssessment)
    composite_risk_score: float = 0.0
    errors: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)


